@register.simple_tag
def icon(name):
    paths = ICONS.get(name, "")
    return mark_safe(
        '<svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
        f"{paths}</svg>"
    )


@register.filter
def compact(value):
    """15500 -> $15.5k, 1200000 -> $1.2M"""
    try:
        n = float(value or 0)
    except (TypeError, ValueError):
        return value
    if n >= 1_000_000:
        s = f"{n / 1_000_000:.1f}M"
    elif n >= 1_000:
        s = f"{n / 1_000:.1f}k"
    else:
        s = f"{n:.0f}"
    return "$" + s.replace(".0", "")
